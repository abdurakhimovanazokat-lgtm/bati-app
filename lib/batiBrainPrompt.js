export function buildUserMessage(question, childAgeText, cards, premiumBundle) {
  var message = childAgeText
    ? "Возраст ребёнка: " + childAgeText + ". Вопрос родителя: " + question
    : question;

  if (cards && cards.length > 0) {
    var cardsList = cards
      .map(function (c) {
        return "- id: " + c.id + ", title: \"" + c.title + "\", url: " + c.url;
      })
      .join("\n");
    message += "\n\nБЕСПЛАТНЫЕ КАРТОЧКИ (используй только эти, максимум 2, точно с этими title/url):\n" + cardsList;
  } else {
    message += "\n\nБЕСПЛАТНЫЕ КАРТОЧКИ: список пуст. Не пиши блок 'BATI Card'.";
  }

  if (premiumBundle) {
    message += "\n\nPREMIUM ГИД (используй точно этот title/url, если уместно предложить):\n";
    message += "- id: " + premiumBundle.id + ", title: \"" + premiumBundle.title + "\", url: " + premiumBundle.url;
  } else {
    message += "\n\nPREMIUM ГИД: не передан. Не пиши блок 'Полный гид BATI'.";
  }

  return message;
}

