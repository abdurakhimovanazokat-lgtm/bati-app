export default function BatiApp() {
  const [screen, setScreen] = useState("loading");
  const [user, setUser] = useState(null);
  useEffect(() => {
    const saved = loadUser();
    if (saved) { setUser(saved); setScreen("today"); }
    else setScreen("splash");
  }, []);
  if (screen === "loading") return null;
  if (screen === "splash") return <Splash onNext={() => setScreen("onboard")} />;
  if (screen === "onboard") return <Onboarding onDone={u => { setUser(u); setScreen("today"); }} />;
  return <Today user={user} onReset={() => { localStorage.removeItem(KEY); setScreen("splash"); }} />;
}
const root = ReactDOM.createRoot(document.getElementById("root"));
root.render(<BatiApp />);
